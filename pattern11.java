

public class pattern11 {
	    public static void main(String[] args) {
	        int n = 5;
	        int valu=1;
	        for(int i=1;i<=n;i++){
	            for(int j=0;j<i;j++){
	             System.out.print(valu);
	             valu++;
	            }
	            System.out.println();
	        }
	    }
	}
